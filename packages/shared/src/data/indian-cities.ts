export type CityLocation = { city: string; state: string };

/** All cities, sorted by city name. */
export const INDIAN_CITIES: readonly CityLocation[] = Object.entries(CITIES_BY_STATE)
  .flatMap(([state, cities]) => cities.map((city) => ({ city, state })))
  .sort((a, b) => a.city.localeCompare(b.city));

const KEYS = new Set(INDIAN_CITIES.map((c) => `${c.city}|${c.state}`));

export const isKnownCity = (loc: CityLocation) => KEYS.has(`${loc.city}|${loc.state}`);

/** "Matheran, Maharashtra" */
export const formatLocation = (loc: CityLocation) => `${loc.city}, ${loc.state}`;
