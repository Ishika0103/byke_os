import { useState, type ReactNode } from 'react';
import { StyleSheet, View } from 'react-native';
import {
  INDIAN_CITIES,
  createHotelSchema,
  updateHotelSchema,
  type CityLocation,
  type Hotel,
} from '@byke-os/shared';

import { Banner } from '@/components/ui/banner';
import { Button } from '@/components/ui/button';
import { Card } from '@/components/ui/card';
import type { Option } from '@/components/ui/option-dialog';
import { Screen } from '@/components/ui/screen';
import { SectionLabel } from '@/components/ui/section-label';
import { SelectField } from '@/components/ui/select-field';
import { StatusToggle } from '@/components/ui/status-toggle';
import { TextField } from '@/components/ui/text-field';
import { Spacing } from '@/constants/theme';
import { apiErrorToForm, issuesToFieldErrors, type FieldErrors } from '@/lib/form-errors';
import { hotelsApi } from '../api/hotels.api';
import { TIME_OPTIONS } from '../utils/time';

const CODE_FIELDS = { NAME_TAKEN: 'name' };

const cityKey = (c: CityLocation) => `${c.city}|${c.state}`;
const CITY_OPTIONS: Option[] = INDIAN_CITIES.map((c) => ({
  value: cityKey(c),
  label: c.city,
  description: c.state,
}));
const cityFromKey = (key: string): CityLocation => {
  const [city, state] = key.split('|');
  return { city, state };
};

/**
 * Add hotel (no `hotel`) or edit hotel, as a full screen with Save pinned at the bottom.
 * The code is generated by the API from the name. Status: a plain switch when adding; on the edit
 * screen it has its own toggle with a confirmation (passed in as `children`).
 */
export function HotelForm({
  hotel,
  header,
  onSaved,
  children,
}: {
  hotel?: Hotel;
  header: ReactNode;
  onSaved: () => void;
  children?: ReactNode;
}) {
  const editing = !!hotel;
  const [name, setName] = useState(hotel?.name ?? '');
  const [isActive, setIsActive] = useState(true);
  const [location, setLocation] = useState<string | null>(hotel ? cityKey(hotel.location) : null);
  const [checkInTime, setCheckInTime] = useState(hotel?.checkInTime ?? '14:00');
  const [checkOutTime, setCheckOutTime] = useState(hotel?.checkOutTime ?? '11:00');
  const [errors, setErrors] = useState<FieldErrors>({});
  const [formError, setFormError] = useState<string | null>(null);
  const [saving, setSaving] = useState(false);

  async function save() {
    setFormError(null);
    const loc = location ? cityFromKey(location) : undefined;
    try {
      if (hotel) {
        // Send only what changed.
        const changes = {
          ...(name.trim() !== hotel.name && { name }),
          ...(location !== cityKey(hotel.location) && { location: loc }),
          ...(checkInTime !== hotel.checkInTime && { checkInTime }),
          ...(checkOutTime !== hotel.checkOutTime && { checkOutTime }),
        };
        if (Object.keys(changes).length === 0) return onSaved();
        const parsed = updateHotelSchema.safeParse(changes);
        if (!parsed.success) return setErrors(issuesToFieldErrors(parsed.error.issues));
        setErrors({});
        setSaving(true);
        await hotelsApi.update(hotel.id, parsed.data);
      } else {
        const parsed = createHotelSchema.safeParse({
          name,
          location: loc,
          checkInTime,
          checkOutTime,
          isActive,
        });
        if (!parsed.success) {
          const fieldErrors = issuesToFieldErrors(parsed.error.issues);
          if (!loc) fieldErrors.location = 'Choose a city';
          return setErrors(fieldErrors);
        }
        setErrors({});
        setSaving(true);
        await hotelsApi.create(parsed.data);
      }
      onSaved();
    } catch (e) {
      const { fields, message } = apiErrorToForm(e, CODE_FIELDS);
      setErrors(fields);
      setFormError(message);
      setSaving(false);
    }
  }

  return (
    <Screen
      header={header}
      footer={
        <Button
          title={editing ? 'Save changes' : 'Create hotel'}
          icon={editing ? 'check' : 'add'}
          onPress={save}
          loading={saving}
        />
      }
    >
      {formError ? <Banner message={formError} /> : null}

      <SectionLabel title="Details" />
      <Card>
        <TextField
          label="Hotel name"
          value={name}
          onChangeText={setName}
          error={errors.name}
          placeholder="e.g. The Byke Brightland Resort"
          hint={editing ? undefined : 'A short code is made from the name, e.g. BRG.'}
          autoCapitalize="words"
          editable={!saving}
        />
        {hotel ? (
          <TextField
            label="Code"
            value={hotel.code}
            hint="Made from the hotel name when it was created. It can't be changed."
            editable={false}
          />
        ) : null}
        <SelectField
          label="Location"
          value={location}
          options={CITY_OPTIONS}
          onChange={(v) => {
            setLocation(v);
            setErrors((e) => ({ ...e, location: undefined }));
          }}
          placeholder="Choose a city"
          error={errors.location}
          disabled={saving}
          searchable
          searchPlaceholder="Search city or state"
        />
      </Card>

      <SectionLabel title="Timings" />
      <Card>
        <View style={styles.times}>
          <View style={styles.time}>
            <SelectField
              label="Check-in"
              value={checkInTime}
              options={TIME_OPTIONS}
              onChange={setCheckInTime}
              error={errors.checkInTime}
              disabled={saving}
            />
          </View>
          <View style={styles.time}>
            <SelectField
              label="Check-out"
              value={checkOutTime}
              options={TIME_OPTIONS}
              onChange={setCheckOutTime}
              error={errors.checkOutTime}
              disabled={saving}
            />
          </View>
        </View>
      </Card>

      {editing ? null : (
        <>
          <SectionLabel title="Status" />
          <StatusToggle
            active={isActive}
            onChange={setIsActive}
            description={isActive ? 'Shown in the hotel picker' : 'Hidden from the hotel picker'}
          />
        </>
      )}

      {children}
    </Screen>
  );
}

const styles = StyleSheet.create({
  times: { flexDirection: 'row', gap: Spacing.three },
  time: { flex: 1 },
});
